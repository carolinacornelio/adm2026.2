// Executar somente contra PosBrowserServer (PostgreSQL descartável).
const { chromium, request } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const { randomUUID } = require('crypto');
const baseURL = 'http://127.0.0.1:18765';
const output = path.resolve('docs/inventario/evidencias');
const dia = offset => { const d=new Date();d.setDate(d.getDate()+offset);return new Intl.DateTimeFormat('en-CA',{timeZone:'America/Fortaleza',year:'numeric',month:'2-digit',day:'2-digit'}).format(d); };
(async () => {
    const api=await request.newContext({baseURL});
    const registration=await api.post('/api/auth/cadastro',{data:{email:`inventario-${randomUUID()}@teste.local`,senha:'teste-inventario-123',nome:'Operador da demonstração',empresa:'RyuTech — demonstração',perguntaSeguranca1:'AMIGO_INFANCIA',perguntaSeguranca2:'EMPREGO_SONHOS',perguntaSeguranca3:'CIDADE_PAIS',respostaSeguranca1:'um',respostaSeguranca2:'dois',respostaSeguranca3:'tres'}});
    assert.equal(registration.status(),200,await registration.text());
    const session=await registration.json();
    const headers={Authorization:`Bearer ${session.token}`};
    const call=async(method,url,data)=>{const r=await api[method](url,{headers,data});assert.ok(r.ok(),`${url}: ${r.status()} ${await r.text()}`);return r.status()===204 || !(r.headers()['content-type']||'').includes('json') ? null:r.json();};
    const produto=await call('post','/api/produtos',{nome:'Leite integral 1 L',codigo:'LEITE',precoCompra:3,precoVenda:5.5,estoqueMinimo:2,controlaValidade:true});
    const fornecedor=await call('post','/api/pessoas',{nome:'Fornecedor da demonstração',tipo:'FORNECEDOR'});
    const cliente=await call('post','/api/pessoas',{nome:'Cliente da demonstração',tipo:'CLIENTE'});
    const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || 'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1440,height:1080},timezoneId:'America/Fortaleza'});
    const errors=[];
    context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
    await context.addInitScript(s=>{if(location.hostname!=='127.0.0.1')return;sessionStorage.setItem('authToken',s.token);sessionStorage.setItem('usuario',JSON.stringify(s.usuario));},session);
    try {
        fs.mkdirSync(output,{recursive:true});
        const page=await context.newPage();
        await page.goto(`${baseURL}/compras.html`);
        await page.waitForFunction(()=>document.querySelector('#corpoItensCompra select').options.length>1);
        await page.selectOption('#selectFornecedor',String(fornecedor.fornecedorId));
        await page.locator('#corpoItensCompra [name=produto]').selectOption(String(produto.id));
        await page.locator('#corpoItensCompra [name=quantidade]').fill('4');
        await page.locator('#corpoItensCompra [name=lote]').fill('LEITE-A');
        await page.locator('#corpoItensCompra [name=validade]').fill(dia(5));
        await page.click('#btnAdicionarItemCompra');
        const second=page.locator('#corpoItensCompra tr').nth(1);
        await second.locator('[name=produto]').selectOption(String(produto.id));
        await second.locator('[name=quantidade]').fill('6');
        await second.locator('[name=lote]').fill('LEITE-B');
        await second.locator('[name=validade]').fill(dia(45));
        assert.deepEqual(await page.locator('#corpoItensCompra select').evaluateAll(list=>list.map(s=>s.options.length)),[2,2]);
        await page.click('#btnFinalizarCompra');
        await page.waitForURL('**/dashboard.html');
        const controle=await call('post','/api/produtos',{nome:'Lote vencido para demonstração',codigo:'VENCIDO',precoCompra:1,precoVenda:2});
        await call('post','/api/compras',{fornecedorId:fornecedor.fornecedorId,itens:[{produtoId:controle.id,quantidade:2,lote:'LEGADO-DEMO'}]});
        const lote=(await call('get','/api/inventario/lotes')).find(l=>l.produtoId===controle.id);
        await call('put',`/api/inventario/lotes/${lote.id}/validade`,{lote:lote.lote,validade:dia(-1)});
        await page.goto(`${baseURL}/estoque.html`);
        await page.waitForFunction(()=>document.querySelector('#listaLotes').textContent.includes('LEITE-B'));
        assert.match(await page.locator('#alertasInventario').innerText(),/2 unidades vencidas; 4 a vencer/);
        const pos=await context.newPage();
        await pos.goto(`${baseURL}/pos.html`);
        await pos.waitForFunction(()=>document.querySelector('#sync-status').textContent.includes('Conectado'));
        const started=performance.now();
        const venda=await call('post','/api/pos/vendas',{chaveOperacao:randomUUID(),itens:[{produtoId:produto.id,quantidade:2}],desconto:0,totalEsperado:11,formaPagamento:'DINHEIRO',valorRecebido:20,pagamentoConfirmado:true});
        await page.waitForFunction(()=>[...document.querySelectorAll('#listaEstoque tr')].some(tr=>tr.cells[0].textContent==='Leite integral 1 L' && tr.cells[2].textContent==='8'),null,{timeout:2000});
        const latencyMs=Math.round(performance.now()-started);
        assert.ok(latencyMs<2000,`Latência local: ${latencyMs} ms`);
        await page.screenshot({path:path.join(output,'inventario.png'),fullPage:true});
        const download=page.waitForEvent('download');await page.click('#exportarInventario');
        const file=await download;const csv=fs.readFileSync(await file.path(),'utf8');assert.match(csv,/LEITE-A/);assert.match(csv,/Vencido/);
        await page.evaluate(()=>window.print=()=>{window.__printed=true;});await page.click('#imprimirInventario');
        assert.equal(await page.evaluate(()=>window.__printed),true);
        await page.emulateMedia({media:'print'});
        assert.equal(await page.locator('.sidebar').evaluate(el=>getComputedStyle(el).display),'none');
        await page.emulateMedia({media:'screen'});await page.evaluate(()=>delete document.body.dataset.impressao);
        await page.goto(`${baseURL}/vendas.html`);
        await page.waitForFunction(()=>document.querySelector('#corpoItensVenda select').options.length>1);
        await page.selectOption('#selectCliente',String(cliente.clienteId));
        await page.selectOption('#corpoItensVenda [name=produto]',String(produto.id));
        await page.fill('#corpoItensVenda [name=quantidade]','1');
        await page.click('#btnFinalizarVenda');await page.waitForURL('**/dashboard.html');
        await page.goto(`${baseURL}/historico-vendas.html`);
        await page.locator('#listaHistorico tr').filter({hasText:'Cliente da demonstração'}).locator('[data-detalhe-venda]').click();
        await page.waitForFunction(()=>!document.querySelector('#imprimirComprovante').disabled);
        assert.match(await page.locator('#conteudoDetalhesVenda').innerText(),/RyuTech/);
        assert.match(await page.locator('#conteudoDetalhesVenda').innerText(),/LEITE-A/);
        assert.match(await page.locator('#conteudoDetalhesVenda').innerText(),/não comprova quitação/);
        await page.screenshot({path:path.join(output,'comprovante-erp.png'),fullPage:true});
        await page.evaluate(()=>window.print=()=>{window.__receiptPrinted=true;});await page.click('#imprimirComprovante');
        assert.equal(await page.evaluate(()=>window.__receiptPrinted),true);
        await page.emulateMedia({media:'print'});
        assert.equal(await page.locator('body > .layout').evaluate(el=>getComputedStyle(el).display),'none');
        assert.equal(await page.locator('#detalhesVenda').evaluate(el=>getComputedStyle(el).display),'block');
        await page.emulateMedia({media:'screen'});
        await page.click('#fecharDetalhesVenda');
        await page.goto(`${baseURL}/estoque.html`);await page.setViewportSize({width:390,height:844});
        await page.waitForFunction(()=>document.querySelector('#listaLotes').textContent.includes('LEITE-A'));
        assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Layout móvel excedeu a tela');
        assert.deepEqual(errors,[]);
        const result={data:new Date().toISOString(),ambiente:'PostgreSQL temporário / Edge headless / localhost',ok:true,latenciaVendaAteInventarioMs:latencyMs,casos:['compra com dois lotes e DTO de validade','opções de compra sem duplicação','alertas de vencido e a vencer','atualização visual automática após venda POS','CSV','impressão do inventário','venda ERP com FEFO','comprovante ERP e impressão','layout móvel'],errosJavaScript:errors};
        fs.writeFileSync(path.join(output,'validacao-browser.json'),JSON.stringify(result,null,2));
        console.log(JSON.stringify(result));
    } finally {await context.close();await browser.close();await api.dispose();}
})().catch(e=>{console.error(e);process.exitCode=1;});
